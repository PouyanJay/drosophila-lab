-- Provider pricing, per-call usage, and spend alerts for paid model calls.
-- Prices are USD per one million tokens. Usage rows keep the rates used at call time.
CREATE TABLE lab.model_prices (
 provider text NOT NULL CHECK(provider IN ('openai','anthropic')),
 model text NOT NULL,
 input_per_mtok numeric NOT NULL CHECK(input_per_mtok >= 0),
 output_per_mtok numeric NOT NULL CHECK(output_per_mtok >= 0),
 cache_read_per_mtok numeric CHECK(cache_read_per_mtok >= 0),
 cache_write_per_mtok numeric CHECK(cache_write_per_mtok >= 0),
 currency text NOT NULL DEFAULT 'USD',
 source text NOT NULL DEFAULT 'bundled-snapshot-2026-09-15',
 source_url text,
 updated_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY(provider, model)
);
CREATE TABLE lab.pricing_refreshes (
 id bigserial PRIMARY KEY,
 started_at timestamptz NOT NULL DEFAULT now(),
 finished_at timestamptz,
 source_url text NOT NULL,
 status text NOT NULL CHECK(status IN ('running','succeeded','failed')),
 models_updated integer NOT NULL DEFAULT 0,
 error text
);
CREATE TABLE lab.llm_usage (
 id text PRIMARY KEY,
 user_id text NOT NULL,
 provider text NOT NULL CHECK(provider IN ('openai','anthropic')),
 model text NOT NULL,
 credential_source text NOT NULL CHECK(credential_source IN ('personal','site')),
 key_hint text NOT NULL,
 surface text NOT NULL CHECK(surface IN ('guide','discovery-guide')),
 experiment_id text,
 campaign_id text,
 request_id text,
 input_tokens integer NOT NULL CHECK(input_tokens >= 0),
 output_tokens integer NOT NULL CHECK(output_tokens >= 0),
 cache_read_tokens integer NOT NULL DEFAULT 0 CHECK(cache_read_tokens >= 0),
 cache_write_tokens integer NOT NULL DEFAULT 0 CHECK(cache_write_tokens >= 0),
 reasoning_tokens integer NOT NULL DEFAULT 0 CHECK(reasoning_tokens >= 0),
 cost_usd numeric CHECK(cost_usd >= 0),
 rates text CHECK(rates IS NULL OR jsonb_typeof(rates::jsonb)='object'),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX llm_usage_created ON lab.llm_usage(created_at DESC);
CREATE INDEX llm_usage_experiment ON lab.llm_usage(experiment_id, created_at DESC);
CREATE INDEX llm_usage_model ON lab.llm_usage(provider, model);
CREATE TABLE lab.cost_settings (
 id integer PRIMARY KEY CHECK(id = 1),
 alert_step_usd numeric NOT NULL CHECK(alert_step_usd > 0),
 updated_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO lab.cost_settings(id, alert_step_usd) VALUES (1, 50);
CREATE TABLE lab.spend_alerts (
 id bigserial PRIMARY KEY,
 threshold_usd numeric NOT NULL UNIQUE CHECK(threshold_usd > 0),
 total_usd numeric NOT NULL,
 usage_id text REFERENCES lab.llm_usage(id) ON DELETE SET NULL,
 triggered_at timestamptz NOT NULL DEFAULT now(),
 acknowledged_at timestamptz
);
